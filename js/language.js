let currentLanguage = (typeof localStorage !== 'undefined' && localStorage.getItem('farmlink_lang')) || 'en';

function t(key) {
    if (!key) return '';
    const langDict = TRANSLATIONS[currentLanguage] || TRANSLATIONS.en;
    return langDict[key] || TRANSLATIONS.en[key] || key;
}

function translateDOM(root = document) {
    if (!root || typeof root.querySelectorAll !== 'function') return;

    // Update all elements with data-i18n
    root.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (!key) return;
        const translated = t(key);
        if (!translated) return;

        // Preserve icons if element contains an icon child
        const icon = el.querySelector('i, svg');
        if (icon && el.children.length > 0) {
            const span = el.querySelector('span');
            if (span && !span.hasAttribute('data-i18n')) {
                span.textContent = translated;
                return;
            }
            let updated = false;
            el.childNodes.forEach(node => {
                if (node.nodeType === 3 && node.textContent.trim()) {
                    node.textContent = ' ' + translated + ' ';
                    updated = true;
                }
            });
            if (!updated && !span) {
                const s = document.createElement('span');
                s.textContent = ' ' + translated;
                el.appendChild(s);
            }
        } else {
            el.textContent = translated;
        }
    });

    // Update placeholders with data-i18n-placeholder
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key && t(key)) {
            el.placeholder = t(key);
        }
    });
}

function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'en';
    currentLanguage = lang;
    try {
        localStorage.setItem('farmlink_lang', lang);
    } catch {}

    if (typeof document !== 'undefined') {
        document.documentElement.lang = lang;
        translateDOM(document);

        // Update language selector dropdowns
        document.querySelectorAll('.lang-select-input').forEach(sel => {
            sel.value = lang;
        });

        if (typeof window !== 'undefined' && window.lucide && typeof window.lucide.createIcons === 'function') {
            window.lucide.createIcons();
        }

        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
    }
}

function initLanguage() {
    if (typeof document === 'undefined') return;
    document.documentElement.lang = currentLanguage;
    
    const init = () => {
        setLanguage(currentLanguage);

        document.querySelectorAll('.lang-select-input').forEach(sel => {
            sel.value = currentLanguage;
            sel.removeEventListener('change', handleLanguageChange);
            sel.addEventListener('change', handleLanguageChange);
        });
    };
    
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }
}

function handleLanguageChange(e) {
    setLanguage(e.target.value);
}

initLanguage();

if (typeof window !== 'undefined') {
    window.t = t;
    window.setLanguage = setLanguage;
    window.translateDOM = translateDOM;
    window.translatePage = () => setLanguage(currentLanguage);
    window.FarmLang = {
        t,
        setLanguage,
        getLanguage: () => currentLanguage,
        translateDOM,
        TRANSLATIONS
    };
}

if (typeof module !== 'undefined' && module.exports) {
    module.exports = { TRANSLATIONS, t, setLanguage, currentLanguage, translateDOM };
}
